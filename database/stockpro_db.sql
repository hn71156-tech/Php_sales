CREATE DATABASE IF NOT EXISTS stockpro_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE stockpro_db;

SET FOREIGN_KEY_CHECKS=0;
DROP TABLE IF EXISTS stock_movements;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS purchase_order_items;
DROP TABLE IF EXISTS purchase_orders;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS suppliers;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS users;
SET FOREIGN_KEY_CHECKS=1;

CREATE TABLE users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 full_name VARCHAR(120) NOT NULL,
 role ENUM('admin','staff') NOT NULL DEFAULT 'staff',
 is_active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 description VARCHAR(255) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE suppliers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(150) NOT NULL,
 phone VARCHAR(30) NULL,
 email VARCHAR(150) NULL,
 address VARCHAR(255) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 sku VARCHAR(50) NOT NULL UNIQUE,
 name VARCHAR(180) NOT NULL,
 category_id BIGINT UNSIGNED NOT NULL,
 cost_price DECIMAL(14,2) NOT NULL DEFAULT 0,
 sale_price DECIMAL(14,2) NOT NULL DEFAULT 0,
 stock_qty INT UNSIGNED NOT NULL DEFAULT 0,
 min_stock INT UNSIGNED NOT NULL DEFAULT 5,
 is_active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_products_category FOREIGN KEY(category_id) REFERENCES categories(id),
 INDEX idx_products_name(name),
 INDEX idx_products_stock(stock_qty)
) ENGINE=InnoDB;

CREATE TABLE purchase_orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 purchase_code VARCHAR(40) NOT NULL UNIQUE,
 supplier_id BIGINT UNSIGNED NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 total_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_purchase_supplier FOREIGN KEY(supplier_id) REFERENCES suppliers(id),
 CONSTRAINT fk_purchase_user FOREIGN KEY(created_by) REFERENCES users(id)
) ENGINE=InnoDB;

CREATE TABLE purchase_order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 purchase_order_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 unit_cost DECIMAL(14,2) NOT NULL,
 CONSTRAINT fk_poi_order FOREIGN KEY(purchase_order_id) REFERENCES purchase_orders(id),
 CONSTRAINT fk_poi_product FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB;

CREATE TABLE orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_code VARCHAR(40) NOT NULL UNIQUE,
 customer_name VARCHAR(150) NOT NULL,
 customer_phone VARCHAR(30) NULL,
 total_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
 status ENUM('pending','completed','cancelled') NOT NULL DEFAULT 'pending',
 created_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_orders_user FOREIGN KEY(created_by) REFERENCES users(id),
 INDEX idx_orders_created(created_at),
 INDEX idx_orders_status(status)
) ENGINE=InnoDB;

CREATE TABLE order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 unit_price DECIMAL(14,2) NOT NULL,
 line_total DECIMAL(14,2) NOT NULL,
 CONSTRAINT fk_oi_order FOREIGN KEY(order_id) REFERENCES orders(id),
 CONSTRAINT fk_oi_product FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB;

CREATE TABLE stock_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id BIGINT UNSIGNED NOT NULL,
 movement_type ENUM('in','out','adjustment') NOT NULL,
 quantity INT NOT NULL,
 reference_type VARCHAR(30) NOT NULL,
 reference_id BIGINT UNSIGNED NULL,
 note VARCHAR(255) NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_mov_product FOREIGN KEY(product_id) REFERENCES products(id),
 CONSTRAINT fk_mov_user FOREIGN KEY(created_by) REFERENCES users(id),
 INDEX idx_mov_product_date(product_id,created_at)
) ENGINE=InnoDB;

